#!/usr/bin/env python3
"""Generate the Rust glyph tables in core/src/font/ from BDF bitmap fonts.

Usage (from the repo root):

    python3 tools/fontgen.py

Each entry in FONTS below becomes one `core/src/font/<module>.rs` file
holding a `Font` value. The output is checked in, so the firmware build
never runs this script; re-run it only after changing FONTS or CHARSET.

Bitmap layout (must match `Font` in core/src/font/mod.rs):
  - Glyphs are stored in ascending codepoint order, parallel to `CHARS`.
  - Each glyph is `height` rows, top to bottom, of `ceil(width / 8)` bytes.
  - Within a row, bit 7 of the first byte is the leftmost pixel; 1 = ink.
  - Bits beyond `width` are always 0.
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# (output module name, source BDF, human-readable description)
FONTS = [
    ("terminus_6x12", "fonts/terminus/ter-u12b.bdf", "Terminus Bold 6x12"),
    ("terminus_8x14", "fonts/terminus/ter-u14b.bdf", "Terminus Bold 8x14"),
    ("terminus_12x24", "fonts/terminus/ter-u24b.bdf", "Terminus Bold 12x24"),
]

# Codepoints included in every font. Every size gets exactly the same set,
# so text that renders in one size renders in all of them.
CHARSET = sorted(set(
    list(range(0x20, 0x7F))           # printable ASCII
    + list(range(0xA0, 0x100))        # Latin-1 supplement (£ ° é ü ...)
    + [0x2013, 0x2014,                # en / em dash
       0x2018, 0x2019, 0x201C, 0x201D,  # curly quotes
       0x2022, 0x2026,                # bullet, ellipsis
       0x20AC,                        # euro
       0x2190, 0x2191, 0x2192, 0x2193,  # arrows
       0x25B2, 0x25B6, 0x25BC, 0x25C0,  # triangles
       0x2713,                        # check mark
       0xFFFD]                        # replacement character (fallback glyph)
    + list(range(0x2500, 0x2580))     # box drawing
    + list(range(0x2580, 0x25A0))     # block elements
) - {
    # Not drawn by Terminus: dashed box lines and two edge blocks.
    0x2504, 0x2505, 0x2506, 0x2507, 0x254C, 0x254D, 0x254E, 0x254F,
    0x2594, 0x2595,
})


def parse_bdf(path):
    """Return (width, height, {codepoint: [row ints, MSB = leftmost]})."""
    with open(path, encoding="latin-1") as f:
        lines = f.read().splitlines()
    ascent = descent = width = None
    glyphs = {}
    i = 0
    while i < len(lines):
        parts = lines[i].split()
        key = parts[0] if parts else ""
        if key == "FONT_ASCENT":
            ascent = int(parts[1])
        elif key == "FONT_DESCENT":
            descent = int(parts[1])
        elif key == "FONTBOUNDINGBOX":
            width = int(parts[1])
        elif key == "STARTCHAR":
            enc = bbx = dwidth = None
            i += 1
            while lines[i] != "BITMAP":
                p = lines[i].split()
                if p[0] == "ENCODING":
                    enc = int(p[1])
                elif p[0] == "BBX":
                    bbx = tuple(map(int, p[1:5]))
                elif p[0] == "DWIDTH":
                    dwidth = int(p[1])
                i += 1
            i += 1
            hexrows = []
            while lines[i] != "ENDCHAR":
                hexrows.append(lines[i])
                i += 1
            glyphs[enc] = (bbx, dwidth, hexrows)
        i += 1

    height = ascent + descent
    cells = {}
    for enc, ((bw, bh, bx, by), dwidth, hexrows) in glyphs.items():
        if dwidth != width:
            sys.exit(f"{path}: U+{enc:04X} has advance {dwidth}, font is not monospace")
        rows = [0] * height
        top = ascent - (by + bh)
        for r, hexrow in enumerate(hexrows):
            y = top + r
            if not 0 <= y < height:
                sys.exit(f"{path}: U+{enc:04X} extends outside the cell")
            bits = int(hexrow, 16) >> (len(hexrow) * 4 - bw)
            shift = width - bx - bw
            if shift < 0 or bx < 0:
                sys.exit(f"{path}: U+{enc:04X} extends outside the cell")
            rows[y] = bits << shift
        cells[enc] = rows
    return width, height, cells


def render_module(name, src, desc):
    width, height, cells = parse_bdf(os.path.join(ROOT, src))
    missing = [c for c in CHARSET if c not in cells]
    if missing:
        sys.exit(f"{src}: missing glyphs: " + ", ".join(f"U+{c:04X}" for c in missing))

    bpr = (width + 7) // 8
    out = []
    out.append(f"// @generated by tools/fontgen.py from {src} ({desc}).")
    out.append("// Do not edit by hand. Licensed under the SIL Open Font License 1.1;")
    out.append("// see fonts/terminus/OFL.TXT.")
    out.append("")
    out.append("use super::Font;")
    out.append("")
    out.append(f"pub const WIDTH: u16 = {width};")
    out.append(f"pub const HEIGHT: u16 = {height};")
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append(f"static CHARS: [char; {len(CHARSET)}] = [")
    for k in range(0, len(CHARSET), 8):
        chunk = CHARSET[k:k + 8]
        out.append("    " + " ".join(f"'\\u{{{c:04X}}}'," for c in chunk))
    out.append("];")
    out.append("")
    out.append("#[rustfmt::skip]")
    out.append(f"static BITMAPS: [u8; {len(CHARSET) * height * bpr}] = [")
    for c in CHARSET:
        data = []
        for row in cells[c]:
            data.extend((row << (bpr * 8 - width)).to_bytes(bpr, "big"))
        label = chr(c) if 0x20 < c < 0x7F else f"U+{c:04X}"
        out.append(f"    /* {label} */ " + ",".join(f"0x{b:02X}" for b in data) + ",")
    out.append("];")
    out.append("")
    out.append("pub static FONT: Font = Font::new(WIDTH, HEIGHT, &CHARS, &BITMAPS);")
    out.append("")

    path = os.path.join(ROOT, "core", "src", "font", f"{name}.rs")
    with open(path, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.relpath(path, ROOT)}: {width}x{height}, {len(CHARSET)} glyphs, "
          f"{len(CHARSET) * height * bpr} bytes")


if __name__ == "__main__":
    for entry in FONTS:
        render_module(*entry)
